/** The provider's mark alone, at the size its `className` gives it (16 px by default): the composer's model picker. */
export function ProviderMark({
  provider,
  className,
}: {
  provider: AiProvider;
  className?: string;
}): React.ReactElement {
  const mark = MARKS[provider];
  if (mark) {
    return (
      <svg
        aria-hidden="true"
        className={cn("size-4 shrink-0", className)}
        fill={mark.color ?? "currentColor"}
        viewBox={mark.viewBox}>
        {mark.paths.map((d) => (
          <path d={d} fillRule="evenodd" key={d.slice(0, 24)} />
        ))}
      </svg>
    );
  }
  if (provider === "groq") {
    return (
      <span
        aria-hidden="true"
        className={cn(
          "flex size-4 shrink-0 items-center justify-center rounded-[4px] bg-[#F55036] font-semibold text-[0.5625rem] text-white leading-none",
          className
        )}>
        g
      </span>
    );
  }
  return <GlobeIcon aria-hidden="true" className={cn("size-4 shrink-0 text-muted-foreground", className)} />;
}

/** The provider's mark on a small tile, sized for a settings row. */
export function ProviderLogo({
  provider,
  className,
}: {
  provider: AiProvider;
  className?: string;
}): React.ReactElement {
  return (
    <span
      aria-hidden="true"
      className={cn(
        "flex size-8 shrink-0 items-center justify-center rounded-lg bg-background shadow-xs ring-1 ring-border",
        className
      )}>
      <ProviderMark
        className={provider === "groq" ? "size-5 rounded-md text-[0.6875rem]" : undefined}
        provider={provider}
      />
    </span>
  );
}
